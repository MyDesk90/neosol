// Estado do idioma atual (Padrão: pt)
let currentLanguage = "pt";

// Função para mudar de idioma com animação suave (Fade)
function changeLanguage(lang) {
    if (lang === currentLanguage) return;
    
    // Iniciar animação de fade-out
    document.body.classList.add("page-fade");
    
    setTimeout(() => {
        currentLanguage = lang;
        document.documentElement.lang = lang;
        
        // Atualizar textos baseado no atributo data-i18n
        document.querySelectorAll("[data-i18n]").forEach(element => {
            const key = element.getAttribute("data-i18n");
            if (translations[lang] && translations[lang][key]) {
                // Preservar marcadores HTML se necessário (como tags span)
                if (key === "logo-text") {
                    // Ignorar para manter a lógica do seletor CSS no HTML
                } else {
                    element.textContent = translations[lang][key];
                }
            }
        });

        // Casos especiais (Logo e textos com marcações específicas)
        const logoSpanText = document.querySelector(".logo-text");
        if (logoSpanText) {
            if (lang === "pt") {
                logoSpanText.innerHTML = 'Novas <span class="accent-text">Soluções</span>';
            } else if (lang === "en") {
                logoSpanText.innerHTML = 'Neo <span class="accent-text">Solutions</span>';
            } else if (lang === "it") {
                logoSpanText.innerHTML = 'Neo <span class="accent-text">Soluccione</span>';
            }
        }
        
        // Atualizar classes ativas dos botões de idioma
        document.querySelectorAll(".lang-btn").forEach(btn => {
            btn.classList.remove("active");
        });
        
        const activeBtn = document.getElementById(`btn-lang-${lang}`);
        if (activeBtn) {
            activeBtn.classList.add("active");
        }
        
        // Finalizar animação de fade-in
        document.body.classList.remove("page-fade");
    }, 150);
}

// Tratamento de envio do formulário de contato com feedback visual
function handleFormSubmit(event) {
    event.preventDefault();
    
    const form = document.getElementById("main-contact-form");
    const feedback = document.getElementById("form-feedback-message");
    const submitBtn = document.getElementById("btn-submit-form");
    
    // Desabilitar botão para evitar múltiplos cliques
    submitBtn.disabled = true;
    submitBtn.textContent = currentLanguage === "pt" ? "Enviando..." : (currentLanguage === "en" ? "Sending..." : "Invio in corso...");
    
    // Simular o envio do formulário por AJAX/Fetch
    setTimeout(() => {
        feedback.classList.remove("hidden", "error", "success");
        feedback.classList.add("success");
        feedback.textContent = translations[currentLanguage]["form-success"];
        
        // Limpar os campos do formulário
        form.reset();
        
        // Reabilitar o botão
        submitBtn.disabled = false;
        submitBtn.textContent = translations[currentLanguage]["btn-submit"];
        
        // Esconder a mensagem de sucesso depois de 5 segundos
        setTimeout(() => {
            feedback.classList.add("hidden");
        }, 5000);
    }, 1200);
}

// Efeito de escurecimento suave do Header ao rolar a página
window.addEventListener("scroll", () => {
    const header = document.getElementById("header-nav");
    if (window.scrollY > 50) {
        header.style.padding = "0.75rem 2rem";
        header.style.boxShadow = "0 4px 20px rgba(0, 0, 0, 0.15)";
    } else {
        header.style.padding = "1rem 2rem";
        header.style.boxShadow = "none";
    }
});
